/**
 * Generate build info with commit IDs from all relevant repositories
 * This script is run during the build process to capture git commit information
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function getCommitInfo(repoPath, repoName) {
  try {
    // In CI pull_request builds, HEAD is a merge commit created by GitHub Actions,
    // not the actual PR branch commit. Use BUILD_COMMIT_OVERRIDE to report the real commit.
    const override = repoName === 'lumina_eval' ? process.env.BUILD_COMMIT_OVERRIDE : undefined;
    const commitHash = override || execSync(`git -C "${repoPath}" rev-parse HEAD`, { encoding: 'utf8' }).trim();
    const commitShort = override ? override.substring(0, 8) : execSync(`git -C "${repoPath}" rev-parse --short HEAD`, { encoding: 'utf8' }).trim();
    const commitDate = execSync(`git -C "${repoPath}" log -1 --format=%ci`, { encoding: 'utf8' }).trim();
    const branch = execSync(`git -C "${repoPath}" rev-parse --abbrev-ref HEAD`, { encoding: 'utf8' }).trim();
    
    // Check for uncommitted changes
    let isDirty = false;
    try {
      execSync(`git -C "${repoPath}" diff --quiet`, { encoding: 'utf8' });
      execSync(`git -C "${repoPath}" diff --staged --quiet`, { encoding: 'utf8' });
    } catch {
      isDirty = true;
    }
    
    return {
      name: repoName,
      commit: commitHash,
      commitShort: commitShort,
      commitDate: commitDate,
      branch: branch,
      isDirty: isDirty
    };
  } catch (e) {
    console.warn(`Could not get commit info for ${repoName} at ${repoPath}: ${e.message}`);
    return {
      name: repoName,
      commit: 'unknown',
      commitShort: 'unknown',
      commitDate: 'unknown',
      branch: 'unknown',
      isDirty: false
    };
  }
}

// Define repository paths relative to this script
const extensionDir = path.resolve(__dirname, '..');
const luminaEvalDir = path.resolve(extensionDir, '../../..'); // Root of lumina_eval (extension -> websape -> agentic_web -> lumina_eval)
const ekoPatchDir = path.resolve(extensionDir, '../../thirdparty/eko-patch');
const webarenaPatchDir = path.resolve(extensionDir, '../../thirdparty/webarena-patch');

// Collect commit info from all repositories
const buildInfo = {
  buildTimestamp: new Date().toISOString(),
  repositories: {
    luminaEval: getCommitInfo(luminaEvalDir, 'lumina_eval'),
    ekoPatch: getCommitInfo(ekoPatchDir, 'eko-patch'),
    webarenaPatch: getCommitInfo(webarenaPatchDir, 'webarena-patch')
  }
};

console.log('Build Info Generated:');
console.log(JSON.stringify(buildInfo, null, 2));

// Generate TypeScript file with build info
const tsContent = `/**
 * Auto-generated build information
 * DO NOT EDIT - This file is generated by scripts/generate-build-info.js during build
 * Generated at: ${buildInfo.buildTimestamp}
 */

export interface RepoCommitInfo {
  name: string;
  commit: string;
  commitShort: string;
  commitDate: string;
  branch: string;
  isDirty: boolean;
}

export interface BuildInfo {
  buildTimestamp: string;
  repositories: {
    luminaEval: RepoCommitInfo;
    ekoPatch: RepoCommitInfo;
    webarenaPatch: RepoCommitInfo;
  };
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};

/**
 * Get a formatted string of all commit info for logging
 */
export function getBuildInfoString(): string {
  const repos = BUILD_INFO.repositories;
  return [
    \`Build Time: \${BUILD_INFO.buildTimestamp}\`,
    \`lumina_eval: \${repos.luminaEval.commitShort} (\${repos.luminaEval.branch})\${repos.luminaEval.isDirty ? ' [dirty]' : ''}\`,
    \`eko-patch: \${repos.ekoPatch.commitShort} (\${repos.ekoPatch.branch})\${repos.ekoPatch.isDirty ? ' [dirty]' : ''}\`,
    \`webarena-patch: \${repos.webarenaPatch.commitShort} (\${repos.webarenaPatch.branch})\${repos.webarenaPatch.isDirty ? ' [dirty]' : ''}\`
  ].join(' | ');
}

/**
 * Get commit info as an object for structured logging
 */
export function getBuildInfoForLogs(): Record<string, string> {
  const repos = BUILD_INFO.repositories;
  return {
    buildTimestamp: BUILD_INFO.buildTimestamp,
    luminaEvalCommit: repos.luminaEval.commit,
    luminaEvalBranch: repos.luminaEval.branch,
    ekoPatchCommit: repos.ekoPatch.commit,
    ekoPatchBranch: repos.ekoPatch.branch,
    webarenaPatchCommit: repos.webarenaPatch.commit,
    webarenaPatchBranch: repos.webarenaPatch.branch
  };
}
`;

// Write the TypeScript file
const outputPath = path.join(extensionDir, 'src/utils/build-info.ts');
fs.writeFileSync(outputPath, tsContent);
console.log(`\nBuild info written to: ${outputPath}`);
